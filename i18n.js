const LANGS = [
  { code: "en", label: "EN", full: "English (US)", html: "en" },
  { code: "pt", label: "PT", full: "Português (BR)", html: "pt-BR" },
  { code: "es", label: "ES", full: "Español (PY)", html: "es-PY" }
];

let currentLang = "pt";

function getLang(){ return currentLang; }

/* Escolhe o texto certo de um objeto {pt,en,es} (usado no conteúdo dinâmico).
   Nome curto 'tr' para não colidir com o L global do Leaflet. */
function tr(obj){
  if (!obj) return "";
  return obj[currentLang] || obj.pt || "";
}

function applyLang(lang){
  if (!LANGS.some(l => l.code === lang)) lang = "pt";
  currentLang = lang;
  const dict = I18N[lang];

  document.querySelectorAll("[data-i18n]").forEach(el => {
    if (!el.dataset.i18nOriginal) el.dataset.i18nOriginal = el.innerHTML;
    const key = el.dataset.i18n;
    el.innerHTML = (dict && dict[key]) ? dict[key] : el.dataset.i18nOriginal;
  });

  document.querySelectorAll("[data-i18n-attr]").forEach(el => {
    // formato: "aria-label:chave" ou "placeholder:chave"
    el.dataset.i18nAttr.split(",").forEach(pair => {
      const [attr, key] = pair.split(":").map(s => s.trim());
      const store = "i18nAttr" + attr.replace(/[^a-z]/gi, "");
      if (!el.dataset[store]) el.dataset[store] = el.getAttribute(attr) || "";
      el.setAttribute(attr, (dict && dict[key]) ? dict[key] : el.dataset[store]);
    });
  });

  const meta = LANGS.find(l => l.code === lang);
  document.documentElement.lang = meta.html;
  try { localStorage.setItem("bp-lang", lang); } catch (e) {}

  document.querySelectorAll(".lang__btn").forEach(b => {
    b.classList.toggle("is-active", b.dataset.lang === lang);
    b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
  });

  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

/* Tela de entrada: na primeira visita o usuário escolhe o idioma antes de
   o site carregar. Quem já escolheu entra direto (a troca segue disponível
   no seletor da nav). O evento bp:langready libera o loader. */
(function initLang(){
  let saved = null;
  try { saved = localStorage.getItem("bp-lang"); } catch (e) {}
  const guess = (() => {
    const nav = (navigator.language || "pt").toLowerCase();
    return nav.startsWith("en") ? "en" : nav.startsWith("es") ? "es" : "pt";
  })();

  document.addEventListener("DOMContentLoaded", () => {
    document.querySelectorAll(".lang__btn").forEach(btn => {
      btn.addEventListener("click", () => applyLang(btn.dataset.lang));
    });

    const gate = document.getElementById("langGate");
    const start = lang => {
      applyLang(lang);
      document.dispatchEvent(new CustomEvent("bp:langready", { detail: { gate: !!gate && !saved } }));
    };

    if (!gate || saved){
      if (gate) gate.remove();
      start(saved || guess);
      return;
    }

    applyLang(guess);            // a própria entrada já aparece no idioma provável
    gate.hidden = false;
    document.body.style.overflow = "hidden";
    gate.querySelectorAll(".gate__opt").forEach(btn => {
      btn.addEventListener("click", () => {
        const lang = btn.dataset.lang;
        gate.dataset.chosen = "true";
        document.body.style.overflow = "";
        start(lang);
      });
    });
  });
})();
